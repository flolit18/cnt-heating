// To configure the MAX
/*
  Bias on : D7 = 1, 
  Auto    : D6 = 1,
  3-wires : D4 = 1, # but actually, I messed up the MAX31865 --> so D4 = 0 2 wires, but remember to plug for 3 wires as Pt100 are mostly sold in 3 wires version
  50 Hz filter : D0 = 1

  --> command : 0x80 to do write demand --> # fixed so 0xD1, 0xC3 if non fix
*/
void config_max31865(void){
  uint8_t tx[2] = {
    0x80, 0xD1
  };
  // as I use A1 as CS 
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_RESET);
  HAL_SPI_Transmit(&hspi2, tx, sizeof(tx), 20);
  // repull CS to HIGH
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_SET);
  HAL_Delay(200);
}

// To read the MAX
/*
  We must keep CS at LOW when read, then point at 0x01, the next bits will sequentially come
  out -> take 16 bits RTD = rx[1] concat rx[2], 15 bits + 1 bit of the fault  
*/
uint16_t read_max31865(void){
  uint8_t tx[3] = {
    0x01, 0x00, 0x00
  };
  uint8_t rx[3];
  // Pull CS down
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_RESET);
  HAL_SPI_TransmitReceive(&hspi2, tx, rx, sizeof(rx), 20);
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_SET);
  return (rx[1] << 8 | rx[2]) >> 1;

}

uint8_t max_read_reg(uint8_t addr)
{
    uint8_t tx[2] = { addr, 0x00 };
    uint8_t rx[2];
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_RESET);
    HAL_SPI_TransmitReceive(&hspi2, tx, rx, 2, 20);
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_SET);
    return rx[1];
}
// Module to read RTD to Celcius
float RTD_to_Temp(uint16_t rtd){
  float R = rtd * 430.0f / 32768.0f;
  return (R - 100.0f) / 0.385f;
}
